// Design 0003 step 2: migration v1 → v2. Structured graphs must produce byte-identical
// records (frozen v1 runner vs the tree executor); unstructured ones are reported.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { migrateV1, describeReport, reportIsEmpty, reportNeedsReview } from '../shared/migrate-v1.js';
import { validateWorkflow } from '../server/workflow/schema.js';
import { allSteps } from '../shared/workflow-tree.js';
import { V1_SAMPLES } from './fixtures/v1-samples.js';
import { STRUCTURED, W, rec, E } from './fixtures/v1-cases.js';

const shape = (steps) => steps.map((s) => `${s.id}${s.disabled ? '(off)' : ''}${s.slots ? `{${Object.values(s.slots).map(shape).join('|')}}` : ''}`).join(',');

test('migration: samples become the expected trees with an empty report', () => {
  const a = migrateV1(V1_SAMPLES[0].workflow);
  assert.equal(a.workflow.version, 2);
  assert.equal(shape(a.workflow.steps), 'loopAcc{acc,loopCon{con}}');
  assert.ok(reportIsEmpty(a.report));
  assert.equal(a.workflow.name, 'Account + Contact');
  assert.equal('nodes' in a.workflow || 'edges' in a.workflow, false);
  assert.equal(JSON.stringify(a.workflow).includes('position'), false);
  const b = migrateV1(V1_SAMPLES[1].workflow);
  assert.equal(shape(b.workflow.steps), 'loop{lead,hot{task|}}');
});

test('migration: merge points become the step after the branch', () => {
  assert.equal(shape(migrateV1(STRUCTURED.mergeAfterBranch).workflow.steps), 'l{b{a|},x},y');
  assert.equal(shape(migrateV1(STRUCTURED.nestedBranchMerge).workflow.steps), 'l{b1{a|b2{c|}},j}');
  assert.equal(shape(migrateV1(STRUCTURED.loopInBranchThenMerge).workflow.steps), 'o{b{l{a}|},x}');
  for (const w of Object.values(STRUCTURED)) assert.ok(reportIsEmpty(migrateV1(w).report));
});

test('migration keeps id, config, name, seed and settings; does not touch the input', () => {
  const w = W([rec('a', 'Account', 'acc', [], { count: 4 })], [E('start', 'a')], { seed: 42, settings: { maxRecords: 10 } });
  const before = JSON.stringify(w);
  const { workflow } = migrateV1(w);
  assert.deepEqual(workflow, { version: 2, name: 'test', seed: 42, settings: { maxRecords: 10 }, steps: [{ id: 'a', type: 'record', config: { sobject: 'Account', alias: 'acc', fields: [], count: 4 } }] });
  assert.equal(JSON.stringify(w), before);
});

test('migration: loop body escaping to the done chain duplicates the shared tail (shape 4)', () => {
  const w = W(
    [{ id: 'l', type: 'loop', config: { count: 3 } }, rec('a', 'A', 'a'), rec('c', 'C', 'c', [{ name: 'P', type: 'lookup', options: { ref: 'c' } }]), rec('d', 'D', 'd')],
    [E('start', 'l'), E('l', 'a', 'body'), E('a', 'c'), E('c', 'd'), E('l', 'c', 'done')],
  );
  const { workflow, report } = migrateV1(w);
  assert.equal(shape(workflow.steps), 'l{a,c,d},c_2,d_2');
  assert.deepEqual(report.duplicated, [
    { id: 'c', copyId: 'c_2', alias: 'c', newAlias: 'c2', root: 'c_2' },
    { id: 'd', copyId: 'd_2', alias: 'd', newAlias: 'd2', root: 'c_2', uniqueFields: ['Name'] },
  ]);
  const c2 = workflow.steps[1];
  assert.equal(c2.config.alias, 'c2');
  assert.equal(c2.config.fields[0].options.ref, 'c2', 'references inside the copy follow the rename');
  // One line for the copied sequence (root + "và N bước phía sau"), not one per copied step.
  const items = describeReport(report);
  const copyLines = items.filter((i) => /được nối tới từ nhiều chỗ/.test(i.message));
  assert.equal(copyLines.length, 1);
  assert.match(copyLines[0].message, /nhân thành "c" và "c_2" và 1 bước phía sau \("d_2"\)/);
  assert.match(copyLines[0].message, /"c" → "c2", "d" → "d2"/);
  assert.equal(copyLines[0].nodeId, 'c_2');
});

test('migration: a copied step with a unique field gets a report line (values can repeat)', () => {
  // A small pool (text, firstName, unique): "c" and its copy "c_2" each track their own
  // "seen" set, so the same first name can come out of both.
  const first = [{ name: 'FirstName', type: 'text', options: { mode: 'firstName', unique: true } }];
  const v1 = W(
    [{ id: 'l', type: 'loop', config: { count: 2 } }, rec('a', 'A', 'a', []), rec('c', 'Contact', 'c', first, { count: 3 })],
    [E('start', 'l'), E('l', 'a', 'body'), E('a', 'c'), E('l', 'c', 'done')],
  );
  const { workflow, report } = migrateV1(v1);
  assert.deepEqual(report.duplicated, [{ id: 'c', copyId: 'c_2', alias: 'c', newAlias: 'c2', root: 'c_2', uniqueFields: ['FirstName'] }]);
  const line = describeReport(report).find((i) => i.nodeId === 'c_2' && /duy nhất/.test(i.message));
  assert.ok(line, 'report explains the unique field');
  assert.match(line.message, /giá trị duy nhất có thể trùng giữa "c" và "c_2"/);
  assert.match(line.message, /"FirstName"/);
  assert.match(line.message, /Tiền tố/, 'says how to fix it');
  assert.ok(reportNeedsReview(report));
  // It really happens: across seeds, some first name is generated by both "c" and "c_2".
  let clash = false;
  for (let seed = 1; seed <= 40 && !clash; seed++) {
    const recs = runWorkflow(workflow, { seed, now: NOW }).records;
    const names = (id) => new Set(recs.filter((r) => r.nodeId === id).map((r) => r.fields.FirstName));
    const c = names('c');
    clash = [...names('c_2')].some((n) => c.has(n));
  }
  assert.ok(clash, 'unique values repeat between the original and the copy');
  // The default of the "unique" option comes from the field-type catalogue (email: on).
  const email = [{ name: 'Email', type: 'email', options: {} }];
  const v1e = W([{ id: 'l', type: 'loop', config: { count: 1 } }, rec('c', 'Contact', 'c', email)], [E('start', 'l'), E('l', 'c', 'body'), E('l', 'c', 'done')]);
  assert.equal(migrateV1(v1e).report.duplicated[0].uniqueFields, undefined);
  const fieldTypes = [{ type: 'email', options: [{ key: 'unique', default: true }] }];
  assert.deepEqual(migrateV1(v1e, { fieldTypes }).report.duplicated[0].uniqueFields, ['Email']);
});

test('migration: duplicate node ids keep the last node, like the v1 executor, and are reported', () => {
  const v1 = W([rec('a', 'First', 'a1', []), rec('a', 'Second', 'a2', [])], [E('start', 'a')]);
  const { workflow, report } = migrateV1(v1);
  assert.equal(shape(workflow.steps), 'a');
  assert.equal(workflow.steps[0].config.sobject, 'Second');
  assert.deepEqual(report.duplicateIds, ['a']);
  assert.match(describeReport(report).find((i) => i.nodeId === 'a').message, /cùng id "a".*sau cùng/);
  assert.deepEqual(runWorkflow(workflow, { seed: 1, now: NOW }).records.map((r) => r.sobject), runV1(v1, { seed: 1, now: NOW }).map((r) => r.sobject));
});

test('migration: nesting deeper than maxDepth is cut, reported and fails validation with the depth error', () => {
  for (const kind of ['loop', 'branch']) {
    const N = 5000; // deep enough to overflow the stack with a naive recursion
    const nodes = [];
    const edges = [E('start', 'n0')];
    for (let i = 0; i < N; i++) {
      nodes.push({ id: `n${i}`, type: kind, config: { count: 1 } });
      if (i + 1 < N) edges.push(E(`n${i}`, `n${i + 1}`, kind === 'loop' ? 'body' : 'true'));
    }
    let result;
    assert.doesNotThrow(() => { result = migrateV1(W(nodes, edges)); }, kind);
    const { workflow, report } = result;
    assert.deepEqual(report.tooDeep, ['n33'], kind);
    assert.equal(report.disabled.length, 0, 'the cut part is not appended again');
    assert.match(describeReport(report).find((i) => i.nodeId === 'n33').message, /lồng nhau quá sâu/);
    const { errors } = validateWorkflow(W(nodes, edges));
    assert.ok(errors.some((e) => /lồng nhau quá 32 cấp/.test(e.message)), kind);
    assert.ok(allSteps(workflow).length <= 40);
  }
  // Long *flat* chains of merged branches are not nesting and stay intact.
  const nodes = [];
  const edges = [E('start', 'b0')];
  for (let i = 0; i < 3000; i++) {
    nodes.push({ id: `b${i}`, type: 'branch', config: {} });
    edges.push(E(`b${i}`, `b${i + 1}`, 'true'), E(`b${i}`, `b${i + 1}`, 'false'));
  }
  nodes.push(rec('b3000', 'X', 'x', []));
  const flat = migrateV1(W(nodes, edges));
  assert.ok(reportIsEmpty(flat.report));
  assert.equal(flat.workflow.steps.length, 3001);
});

test('migration: missing loop counts are written as the values the executor uses', () => {
  const v1 = W([{ id: 'f', type: 'loop', config: {} }, { id: 'r', type: 'loop', config: { mode: 'range' } }], [E('start', 'f'), E('f', 'r', 'done')]);
  const [f, r] = migrateV1(v1).workflow.steps;
  assert.equal(f.config.count, 0);
  assert.deepEqual([r.config.min, r.config.max], [1, 1]);
});

test('migration: cross-branch link and two loops sharing a body are duplicated (shapes 5, 6)', () => {
  const cross = W(
    [{ id: 'b1', type: 'branch', config: {} }, { id: 'b2', type: 'branch', config: {} }, rec('a', 'A', 'a'), rec('b', 'B', 'b'), rec('x', 'X', 'x'), rec('z', 'Z', 'z')],
    [E('start', 'b1'), E('b1', 'a', 'true'), E('a', 'x'), E('b1', 'b', 'false'), E('b', 'b2'), E('b2', 'x', 'true'), E('b2', 'z', 'false')],
  );
  const m = migrateV1(cross);
  assert.equal(shape(m.workflow.steps), 'b1{a,x|b,b2{x_2|z}}');
  assert.deepEqual(m.report.duplicated.map((d) => d.copyId), ['x_2']);

  const shared = W(
    [{ id: 'l1', type: 'loop', config: { count: 2 } }, { id: 'l2', type: 'loop', config: { count: 2 } }, rec('a', 'A', 'a')],
    [E('start', 'l1'), E('l1', 'a', 'body'), E('l1', 'l2', 'done'), E('l2', 'a', 'body')],
  );
  assert.equal(shape(migrateV1(shared).workflow.steps), 'l1{a},l2{a_2}');
});

test('migration: unreachable nodes go to the end, disabled (shape 7)', () => {
  const w = W([rec('a', 'A', 'a'), rec('o1', 'O', 'o1'), rec('o2', 'O', 'o2'), { id: 'lp', type: 'loop', config: {} }, rec('in', 'I', 'in')],
    [E('start', 'a'), E('o1', 'o2'), E('lp', 'in', 'body')]);
  const { workflow, report } = migrateV1(w);
  assert.equal(shape(workflow.steps), 'a,o1(off),o2(off),lp(off){in}');
  assert.deepEqual(report.disabled, ['o1', 'o2', 'lp']);
  assert.match(describeReport(report).find((i) => i.nodeId === 'lp').message, /đang tắt/);
});

test('migration: cycles, fan-out and dangling edges are repaired and reported (shape 8)', () => {
  const w = W([rec('a', 'A', 'a'), rec('b', 'B', 'b'), rec('x', 'X', 'x'), rec('y', 'Y', 'y')], [
    E('start', 'a'), E('a', 'b'), E('b', 'a'), // cycle
    { from: 'b', fromPort: 'next', to: 'zz' }, // missing target
    { id: 'br' },
  ]);
  w.nodes.push({ id: 'br', type: 'branch', config: {} });
  w.edges.push(E('x', 'y'), E('br', 'x', 'true'), E('br', 'y', 'true')); // fan-out: last edge (→ y) wins
  const { workflow, report } = migrateV1(w);
  assert.deepEqual(report.droppedEdges.map((e) => `${e.from}>${e.to}:${e.reason}`).sort(), ['b>a:cycle', 'b>zz:missing', 'br>x:fanout', 'undefined>undefined:missing']);
  assert.equal(shape(workflow.steps), 'a,b,x(off),y(off),br(off){y_2|}');
});

test('migration: duplication is capped and the rest is reported as truncated', () => {
  // A chain of loops whose bodies all escape to their done-chain doubles the tree at each level.
  const nodes = [];
  const edges = [E('start', 'l0')];
  const N = 14;
  for (let i = 0; i < N; i++) {
    nodes.push({ id: `l${i}`, type: 'loop', config: { count: 1 } }, rec(`c${i}`, 'C', `c${i}`));
    edges.push(E(`l${i}`, `c${i}`, 'body'), E(`l${i}`, `c${i}`, 'done'));
    if (i + 1 < N) edges.push(E(`c${i}`, `l${i + 1}`));
  }
  const { workflow, report } = migrateV1(W(nodes, edges));
  const total = allSteps(workflow).length;
  assert.ok(total <= 2 * (2 * N + 1) + 50, `tree has ${total} steps`);
  assert.ok(report.truncated.length > 0);
  assert.match(describeReport(report).at(-1).message, /ngừng nhân bản/);
});

test('migration: a v2 workflow is returned unchanged; garbage does not throw', () => {
  const v2 = { version: 2, steps: [] };
  assert.equal(migrateV1(v2).workflow, v2);
  assert.ok(reportIsEmpty(migrateV1(v2).report));
  assert.deepEqual(migrateV1({ version: 1 }).workflow.steps, []);
  assert.deepEqual(migrateV1({ version: 1, nodes: [null, { id: 'a', type: 'record' }], edges: [null] }).workflow.steps.map((s) => s.disabled), [true]);
});

// ---------- equivalence with the frozen v1 runner (needs the tree executor) ----------

import { runWorkflow } from '../server/workflow/executor.js';
import { runV1 } from './fixtures/run-v1.js';
import { NOW } from './helpers.js';

const cases = { ...Object.fromEntries(V1_SAMPLES.map((s) => [`sample "${s.label}"`, s.workflow])), ...STRUCTURED };
for (const [label, v1] of Object.entries(cases)) {
  test(`migration equivalence: ${label} gives byte-identical records`, () => {
    const { workflow, report } = migrateV1(v1);
    assert.ok(reportIsEmpty(report));
    for (const seed of [1, 7, 'seed-x']) {
      const expected = JSON.stringify(runV1(v1, { seed, now: NOW }));
      assert.equal(JSON.stringify(runWorkflow(workflow, { seed, now: NOW }).records), expected);
    }
  });
}

test('migration equivalence: a duplicated tail generates the same values (only nodeId/alias differ)', () => {
  const v1 = W(
    [{ id: 'l', type: 'loop', config: { count: 3 } }, rec('a', 'A', 'a'), rec('c', 'C', 'c')],
    [E('start', 'l'), E('l', 'a', 'body'), E('a', 'c'), E('l', 'c', 'done')],
  );
  const expected = runV1(v1, { seed: 7, now: NOW });
  const actual = runWorkflow(migrateV1(v1).workflow, { seed: 7, now: NOW }).records;
  const strip = (rs) => rs.map((r) => ({ sobject: r.sobject, fields: r.fields }));
  assert.deepEqual(strip(actual), strip(expected));
  assert.equal(actual.at(-1).nodeId, 'c_2');
});
